#[derive(Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
enum Case {
    Inspection(InspectionCase),
    Permission {
        schema: u32,
        id: String,
        mode: String,
        expression: String,
        allow: Vec<String>,
        expected: bool,
    },
    Expiry {
        schema: u32,
        id: String,
        mode: String,
        date: String,
        expires: String,
        expected: bool,
    },
}

#[derive(Deserialize)]
struct InspectionCase {
    expression: String,
    schema: u32,
    id: String,
    mode: String,
    slots: Vec<u8>,
    required: bool,
    permitted: bool,
    anomaly: u8,
    #[serde(flatten)]
    escalation: Escalation,
    expected: u8,
}

#[derive(Deserialize)]
struct Escalation {
    warnings: bool,
    deny: bool,
}

